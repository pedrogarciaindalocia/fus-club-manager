/**
 * Registre des classements statiques par catégorie
 */
export const STATIC_STANDINGS_BY_CATEGORY: Record<string, StandingRow[]> = {
  'U21': U21_STATIC_STANDINGS,
};

/**
 * Récupère le classement statique d'une catégorie donnée.
 */
export function getStaticStandingsForCategory(category?: string | null): StandingRow[] | null {
  if (!category) return null;
  const upper = category.trim().toUpperCase();
  for (const [cat, standings] of Object.entries(STATIC_STANDINGS_BY_CATEGORY)) {
    if (upper === cat || upper.includes(cat) || cat.includes(upper)) {
      return standings;
    }
  }
  return null;
}
